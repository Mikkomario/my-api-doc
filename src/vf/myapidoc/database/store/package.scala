package vf.myapidoc.database

import utopia.flow.collection.CollectionExtensions._
import utopia.flow.collection.immutable.{Empty, OptimizedIndexedSeq}
import utopia.flow.util.NotEmpty
import utopia.vault.store.HasId

/**
 * Provides utility functions for the DB interfaces
 * @author Mikko Hilpinen
 * @since 26.10.2026, v0.1
 */
package object store
{
	/**
	 * Updates an exclusive set of items
	 * @param existingEntries Existing DB entries
	 * @param newEntries New / updated entries (exclusive list)
	 * @param existingToKey A function that converts an existing item to a unique key
	 * @param newToKey A function that converts a new entry into a unique key (compatible with 'existingToKey')
	 * @param updateExisting A function that receives:
	 *                       1. An existing item
	 *                       1. A matching update (based on the extracted key)
	 *
	 *                       And executes the update.
	 *                       Yields one result.
	 * @param deprecateIds A function that receives 1 or more existing item IDs and deprecates their entries.
	 * @param insertEntries A function that receives 1 or more new entries and inserts them to the DB.
	 *                      Yields n results (usually one for each inserted item).
	 * @tparam E Type of the existing items
	 * @tparam N Type of the new entries
	 * @tparam K Type of the used keys
	 * @tparam R Type of generated results
	 * @return Results generated by 'updateExisting' and 'insertEntries'
	 */
	def updateExclusiveMatches[E <: HasId[Int], N, K, R](existingEntries: IterableOnce[E], newEntries: IterableOnce[N])
	                                                    (existingToKey: E => K)(newToKey: N => K)
	                                                    (updateExisting: (E, N) => R)
	                                                    (deprecateIds: Set[Int] => Unit)
	                                                    (insertEntries: Seq[N] => IterableOnce[R]) =
		existingEntries.nonEmptyIterator match {
			case Some(existingIter) =>
				newEntries.nonEmptyCollection match {
					// Case: Both existing and new entries are present => Matches existing and new items
					case Some(newEntries) =>
						val resultsBuilder = OptimizedIndexedSeq.newBuilder[R]
						
						val existingByKey = existingIter.map { e => existingToKey(e) -> e }.toMap
						val (entriesToInsert, matchedExistingIds) = newEntries.divideWith { newEntry =>
							val key = newToKey(newEntry)
							existingByKey.get(key) match {
								// Case: Match => Updates the existing item
								case Some(existing) =>
									resultsBuilder += updateExisting(existing, newEntry)
									Right(existing.id)
									
									// Case: No match => Prepares an insert
								case None => Left(newEntry)
							}
						}
						
						// Deprecates all unmatched existing items
						NotEmpty(existingByKey.valuesIterator.map { _.id }.toSet -- matchedExistingIds)
							.foreach(deprecateIds)
						// Performs the inserts
						if (entriesToInsert.nonEmpty)
							resultsBuilder ++= insertEntries(entriesToInsert)
						
						resultsBuilder.result()
						
						// Case: There are no new entries => Deprecates all existing items
					case None =>
						deprecateIds(existingIter.map { _.id }.toSet)
						Empty
				}
				// Case: There are no existing entries => Inserts the new entries, if present
			case None =>
				newEntries.nonEmptyCollection match {
					case Some(newEntries) => insertEntries(newEntries.toOptimizedSeq).toOptimizedSeq
					case None => Empty
				}
		}
	
	/**
	 * Standardizes a reference so that it may be used in Maps
	 * @param reference A reference to standardize
	 * @return Standardized version of the specified reference
	 */
	def standardizeRef(reference: String) = reference.filter { _.isLetter }.toLowerCase
}
